// Run: node tests/sync-health.test.cjs
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'..','sync-health.js'),'utf8');
new vm.Script(source);
const from=source.indexOf(' function describe(');
const to=source.indexOf(' let lastStatus=',from);
assert(from>=0&&to>from,'Cannot extract save-state classification');
const {describe}=vm.runInNewContext(source.slice(from,to)+'\n({describe})');
let passed=0;
const check=(name,run)=>{run();console.log('PASS '+name);passed++};
check('only confirmed cloud status displays green',()=>assert.equal(describe('Saved to cloud',true,false,true).type,'synced'));
check('successful cloud restore shows confirmed backup',()=>assert.equal(describe('Updated from cloud',true,false,true).type,'synced'));
check('cloud restore with pending local edits is not confirmed',()=>assert.notEqual(describe('Updated from cloud',true,true,true).type,'synced'));
check('cloud status requires account link',()=>assert.notEqual(describe('Updated from cloud',false,false,true).type,'synced'));
check('confirmed cloud with pending edits not green',()=>assert.notEqual(describe('Saved to cloud',true,true,true).type,'synced'));
check('offline linked account is visibly warned',()=>assert.equal(describe('Offline',true,true,false).type,'warning'));
check('signed out says device not cloud',()=>assert.equal(describe('Not connected',false,false,true).text,'Saved on this device'));
check('signed-out local edit remains a local success',()=>assert.equal(describe('Local change',false,false,true).text,'Saved on this device'));
check('signed-out device does not claim cloud pending after return online',()=>assert.equal(describe('Online',false,false,true).text,'Saved on this device'));
check('local edits never claim cloud success',()=>assert.equal(describe('Local change',true,false,true).type,'pending'));
check('cloud connection failure is a warning',()=>assert.equal(describe('Connection issue',true,true,true).type,'warning'));
check('saving state shown as pending',()=>assert.equal(describe('Syncing',true,true,true).type,'pending'));
check('copy selection not mistaken for complete cloud save',()=>assert.equal(describe('Choose a copy',true,false,true).type,'pending'));
console.log('Passed '+passed+' save-status checks.');
